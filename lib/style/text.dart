/// SwiftUI-compatible text scale options.
enum CNTextScale {
  /// The default text scale.
  defaultScale,

  /// Secondary text scale.
  secondary,
}

/// SwiftUI-compatible truncation modes for text.
enum CNTextTruncationMode {
  /// Truncate at the beginning.
  head,

  /// Truncate in the middle.
  middle,

  /// Truncate at the end.
  tail,
}
