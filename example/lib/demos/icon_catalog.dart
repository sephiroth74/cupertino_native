// Icon name catalogs shared by the demo pages.
//
// The `Icons` / `CupertinoIcons` entries were extracted from the Flutter SDK
// icon fonts; the SF Symbol entries are macOS symbol names resolved natively by
// `CNImage`. Keys are the identifiers you would type in code, so the demos can
// show the name next to each glyph and copy it to the clipboard.

import 'package:flutter/cupertino.dart';
import 'package:flutter/material.dart';

/// The icon families the demos can browse.
///
/// Demo-only: it selects which catalog to list, it is not a widget-level API.
/// The families are not interchangeable — [material] and [cupertino] resolve to
/// a Flutter [IconData] (a glyph in a bundled font), while [sfSymbol] only
/// yields a name that macOS resolves natively, one platform view per icon.
enum IconSource {
  /// Flutter's Material `Icons` set.
  material('Icons'),

  /// Flutter's `CupertinoIcons` set.
  cupertino('CupertinoIcons'),

  /// Native macOS SF Symbols, resolved by name on the platform side.
  sfSymbol('SF Symbols');

  const IconSource(this.label);

  /// Human readable name, used as the picker tag.
  final String label;

  /// The number of icons available in this family.
  int get length => switch (this) {
    IconSource.material => kMaterialIcons.length,
    IconSource.cupertino => kCupertinoIcons.length,
    IconSource.sfSymbol => kSFSymbolNames.length,
  };

  /// The icon names of this family, in catalog order.
  List<String> get names => switch (this) {
    IconSource.material => kMaterialIcons.keys.toList(growable: false),
    IconSource.cupertino => kCupertinoIcons.keys.toList(growable: false),
    IconSource.sfSymbol => kSFSymbolNames,
  };

  /// The Flutter [IconData] for [name], or `null` for [IconSource.sfSymbol]
  /// (those are drawn natively from their symbol name instead).
  IconData? iconData(String name) => switch (this) {
    IconSource.material => kMaterialIcons[name],
    IconSource.cupertino => kCupertinoIcons[name],
    IconSource.sfSymbol => null,
  };
}

